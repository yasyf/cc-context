const regenCat = "cat src/*.txt > gen/out.txt"

var regenMissingSrc = regexp.MustCompile(`cat: '?src/\*\.txt'?: No such file or directory`)

func regenRepo(t *testing.T, run string) *vcstest.Fixture {
	t.Helper()
	f := shipGTRepo(t)
	writeShipFile(t, f.Dir, regenFile, fmt.Sprintf("[[generated]]\npaths = [\"gen/*.txt\"]\nrun = %q\n", run))
	writeShipFile(t, f.Dir, "src/a.txt", "a\n")
	writeShipFile(t, f.Dir, "gen/out.txt", "a\n")
	writeShipFile(t, f.Dir, "gen/other.txt", "other\n")
	mustRun(t, f.Env(), f.Dir, "git", "add", "-A")
	mustRun(t, f.Env(), f.Dir, "git", "commit", "-qm", "generated")
	mustRun(t, f.Env(), f.Dir, "git", "push", "-q", "origin", "main")
	return f
}

func regenBranch(t *testing.T, f *vcstest.Fixture, files map[string]string, removed ...string) {
	t.Helper()
	mustRun(t, f.Env(), f.Dir, "git", "switch", "-qc", "feature")
	for name, content := range files {
		writeShipFile(t, f.Dir, name, content)
	}
	for _, name := range removed {
		mustRun(t, f.Env(), f.Dir, "git", "rm", "-q", name)
	}
	mustRun(t, f.Env(), f.Dir, "git", "add", "-A")
	mustRun(t, f.Env(), f.Dir, "git", "commit", "-qm", "feature")
	mustRun(t, f.Env(), f.Dir, "gt", "track", "-f", "--no-interactive")
}

func regenAdvanceTrunk(t *testing.T, f *vcstest.Fixture, files ...[2]string) {
	t.Helper()
	for _, file := range files {
		restackAdvanceRemote(t, f, "main", file[0], file[1])
	}
	mustRun(t, f.Env(), f.Dir, "git", "fetch", "-q", "origin")
	shipResetLog(t, f)
}

func regenMarked(t *testing.T, run string) (string, string) {
	t.Helper()
	marker := filepath.Join(t.TempDir(), "ran")
	return fmt.Sprintf("echo ran >> '%s'; %s", marker, run), marker
}

func regenRuns(t *testing.T, marker string) int {
	t.Helper()
	raw, err := os.ReadFile(marker)
	if errors.Is(err, fs.ErrNotExist) {
		return 0
	}
	if err != nil {
		t.Fatal(err)
	}
	return strings.Count(string(raw), "ran\n")
}

func regenStop(t *testing.T, f *vcstest.Fixture) (string, error) {
	t.Helper()
	feature := gitAt(t, f.Env(), f.Dir, "rev-parse", "feature")
	_, _, err := runStackCmd(t, f, "rebase", "--no-push")
	if err == nil {
		t.Fatal("stack rebase succeeded, want the conflict to stop it")
	}
	if got := gitAt(t, f.Env(), f.Dir, "rev-parse", "feature"); got != feature {
		t.Errorf("feature moved to %s on a stopped rebase", got)
	}
	return stackWorkspaceOf(t, err), err
}

func regenSection(cmd string) string {
	return "generated by " + regenFile + ":\n  gen/out.txt" + shipSep + cmd + "\nregenerate: ccx vcs stack regenerate"
}

func TestStackRebasePlansAStopForAGeneratedConflict(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name    string
		files   map[string]string
		removed []string
		trunk   [][2]string
		want    bool
	}{
		{"changed on both sides", map[string]string{"src/f.txt": "f\n", "gen/out.txt": "a\nf\n"}, nil, [][2]string{{"src/t.txt", "t\n"}, {"gen/out.txt", "a\nt\n"}}, true},
		{"deleted by the branch", nil, []string{"gen/out.txt"}, [][2]string{{"gen/out.txt", "a\nt\n"}}, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			f := regenRepo(t, regenCat)
			regenBranch(t, f, tt.files, tt.removed...)
			regenAdvanceTrunk(t, f, tt.trunk...)

			plan, _, err := runStackCmd(t, f, "rebase", "--dry-run")
			if err != nil {
				t.Fatalf("dry run: %v", err)
			}
			line := "feature" + shipSep + "gen/out.txt generated" + shipSep + "a conflict there stops for ccx vcs stack regenerate" + shipSep + regenCat
			if got := strings.Contains(plan, line); got != tt.want {
				t.Errorf("plan = %q, want line %q present = %v", plan, line, tt.want)
			}
			if !tt.want && strings.Contains(plan, "generated") {
				t.Errorf("plan = %q, want no generated line for a path the branch deletes", plan)
			}
		})
	}
}

// TestStackRebaseStopsOnAGeneratedOnlyConflict pins the explicit-only design:
// a conflict every generator could settle still stops, and neither the rebase
// nor a refused continue runs a generator.
func TestStackRebaseStopsOnAGeneratedOnlyConflict(t *testing.T) {
	t.Parallel()
	cmd, marker := regenMarked(t, regenCat)
	f := regenRepo(t, cmd)
	regenBranch(t, f, map[string]string{"src/f.txt": "f\n", "gen/out.txt": "a\nf\n"})
	regenAdvanceTrunk(t, f, [2]string{"src/t.txt", "t\n"}, [2]string{"gen/out.txt", "a\nt\n"})

	ws, err := regenStop(t, f)
	for _, want := range []string{
		"workspace: " + ws + " (detached, sparse, rebase in progress, rerere off)",
		"conflicted files:\n  gen/out.txt\n",
		regenSection(cmd) + " [--include <dir>]... [--full], from " + ws + " once every other file is resolved",
	} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("brief = %v, want %q", err, want)
		}
	}
	if n := regenRuns(t, marker); n != 0 {
		t.Errorf("the generator ran %d time(s) during the rebase, want none", n)
	}
	if unmerged := gitAt(t, f.Env(), ws, "diff", "--name-only", "--diff-filter=U"); unmerged != "gen/out.txt" {
		t.Errorf("unmerged = %q, want gen/out.txt", unmerged)
	}

	_, _, err = runStackCmd(t, f, "continue")
	if err == nil {
		t.Fatal("continue succeeded over an unresolved generated file")
	}
	for _, want := range []string{
		ws + " still has unresolved files: gen/out.txt — resolve them and git add them first\n" + regenSection(cmd),
		"from " + ws + " once every other file is resolved",
	} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("continue = %v, want %q", err, want)
		}
	}
	if n := regenRuns(t, marker); n != 0 {
		t.Errorf("the generator ran %d time(s) during a refused continue, want none", n)
	}
	if unmerged := gitAt(t, f.Env(), ws, "diff", "--name-only", "--diff-filter=U"); unmerged != "gen/out.txt" {
		t.Errorf("unmerged after continue = %q, want gen/out.txt", unmerged)
	}
}

// TestStackRegenerateChecksOutWhatItIsAskedTo pins that the conflict workspace
// holds only the root files and the conflicted directories, so a generator
// reading src/ fails until --include src or --full checks it out.
func TestStackRegenerateChecksOutWhatItIsAskedTo(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name     string
		flags    []string
		wantCone string
		wantLib  bool
	}{
		{"include", []string{"--include", "src"}, "gen\nsrc", false},
		{"full", []string{"--full"}, "", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			cmd, marker := regenMarked(t, regenCat)
			f := regenRepo(t, cmd)
			regenBranch(t, f, map[string]string{"src/f.txt": "f\n", "gen/out.txt": "a\nf\n", "lib/keep.txt": "keep\n"})
			regenAdvanceTrunk(t, f, [2]string{"src/t.txt", "t\n"}, [2]string{"gen/out.txt", "a\nt\n"})
			ws, _ := regenStop(t, f)
			if cone := gitAt(t, f.Env(), ws, "sparse-checkout", "list"); cone != "gen" {
				t.Errorf("cone = %q, want only the conflicted gen", cone)
			}
			for _, name := range []string{"src", "lib"} {
				if _, err := os.Stat(filepath.Join(ws, name)); !errors.Is(err, fs.ErrNotExist) {
					t.Errorf("%s in the workspace: %v, want it not checked out", name, err)
				}
			}

			_, _, err := runStackCmdIn(t, f, ws, "regenerate")
			if err == nil {
				t.Fatal("regenerate succeeded without src checked out")
			}
			for _, want := range []string{"stack regenerate: regenerating gen/out.txt failed, and nothing was committed", "generator `" + cmd + "` exited 1"} {
				if !strings.Contains(err.Error(), want) {
					t.Errorf("regenerate = %v, want %q", err, want)
				}
			}
			if !regenMissingSrc.MatchString(err.Error()) {
				t.Errorf("regenerate = %v, want cat's missing src/*.txt, quoted by GNU cat or not by BSD cat", err)
			}
			if unmerged := gitAt(t, f.Env(), ws, "diff", "--name-only", "--diff-filter=U"); unmerged != "gen/out.txt" {
				t.Errorf("unmerged after a failed regenerate = %q, want gen/out.txt", unmerged)
			}

			out, _, err := runStackCmdIn(t, f, ws, append([]string{"regenerate"}, tt.flags...)...)
			if err != nil {
				t.Fatalf("regenerate %v: %v", tt.flags, err)
			}
			if want := "regenerated gen/out.txt" + shipSep + cmd + "\nnext: ccx vcs stack continue"; out != want {
				t.Errorf("regenerate output = %q, want %q", out, want)
			}
			if n := regenRuns(t, marker); n != 2 {
				t.Errorf("the generator ran %d time(s), want once per regenerate", n)
			}
			if got, err := os.ReadFile(filepath.Join(ws, "gen", "out.txt")); err != nil || string(got) != "a\nf\nt\n" {
				t.Errorf("regenerated gen/out.txt = %q, %v, want a, f, t", got, err)
			}
			if tt.wantCone != "" {
				if cone := gitAt(t, f.Env(), ws, "sparse-checkout", "list"); cone != tt.wantCone {
					t.Errorf("cone = %q, want %q", cone, tt.wantCone)
				}
			} else if sparse := gitAt(t, f.Env(), ws, "config", "--get", "core.sparseCheckout"); sparse != "false" {
				t.Errorf("core.sparseCheckout = %q, want false after --full", sparse)
			}
			if tt.wantLib {
				for _, name := range strings.Split(gitAt(t, f.Env(), ws, "ls-files"), "\n") {
					if _, err := os.Stat(filepath.Join(ws, name)); err != nil {
						t.Errorf("tracked %s after --full: %v, want it on disk", name, err)
					}
				}
			} else if _, err := os.Stat(filepath.Join(ws, "lib")); !errors.Is(err, fs.ErrNotExist) {
				t.Errorf("lib after --include src: %v, want it still not checked out", err)
			}

			if _, _, err := runStackCmdIn(t, f, ws, "continue"); err != nil {
				t.Fatalf("continue: %v", err)
			}
			if !stackOnto(t, f, "origin/main", "feature") {
				t.Error("feature is not on the new trunk")
			}
			if got := gitAt(t, f.Env(), f.Dir, "show", "feature:gen/out.txt"); got != "a\nf\nt" {
				t.Errorf("feature's gen/out.txt = %q, want the regenerated a, f, t", got)
			}
			if n := gitAt(t, f.Env(), f.Dir, "rev-list", "--count", "origin/main..feature"); n != "1" {
				t.Errorf("feature holds %s commits over trunk, want its own 1", n)
			}
		})
	}
}

// TestStackBriefReadsTheWorkspaceAfterRegenerateFull pins that a stop after
// regenerate --full describes the workspace it left: every file checked out and
// no sparse cone to widen, rather than the sparse workspace the first stop cut.
func TestStackBriefReadsTheWorkspaceAfterRegenerateFull(t *testing.T) {
	t.Parallel()
	f := regenRepo(t, regenCat)
	writeShipFile(t, f.Dir, "docs/x.txt", "base\n")
	mustRun(t, f.Env(), f.Dir, "git", "add", "docs/x.txt")
	mustRun(t, f.Env(), f.Dir, "git", "commit", "-qm", "docs")
	mustRun(t, f.Env(), f.Dir, "git", "push", "-q", "origin", "main")
	regenBranch(t, f, map[string]string{"src/f.txt": "f\n", "gen/out.txt": "a\nf\n"})
	writeShipFile(t, f.Dir, "docs/x.txt", "branch\n")
	mustRun(t, f.Env(), f.Dir, "git", "commit", "-qam", "docs on the branch")
	regenAdvanceTrunk(t, f, [2]string{"src/t.txt", "t\n"}, [2]string{"gen/out.txt", "a\nt\n"}, [2]string{"docs/x.txt", "trunk\n"})

	ws, err := regenStop(t, f)
	if want := "workspace: " + ws + " (detached, sparse, rebase in progress, rerere off)"; !strings.Contains(err.Error(), want) {
		t.Fatalf("first brief = %v, want %q", err, want)
	}
	if _, _, err := runStackCmdIn(t, f, ws, "regenerate", "--full"); err != nil {
		t.Fatalf("regenerate --full: %v", err)
	}

	_, _, err = runStackCmdIn(t, f, ws, "continue")
	if err == nil {
		t.Fatal("continue succeeded, want the docs/x.txt conflict to stop it")
	}
	brief := err.Error()
	for _, want := range []string{
		"workspace: " + ws + " (detached, rebase in progress, rerere off)",
		"conflicted files:\n  docs/x.txt\n",
		"checked out: every file\n",
	} {
		if !strings.Contains(brief, want) {
			t.Errorf("second brief = %q, want %q", brief, want)
		}
	}
	if strings.Contains(brief, "sparse") {
		t.Errorf("second brief = %q, want no sparse wording for a full workspace", brief)
	}
	if sparse := gitAt(t, f.Env(), ws, "config", "--get", "core.sparseCheckout"); sparse != "false" {
		t.Errorf("core.sparseCheckout = %q, want false after --full", sparse)
	}
}

// TestStackRegenHintReadsTheWorkspaceAfterRegenerateFull pins that a later
// generated conflict in a workspace regenerate --full already checked out in
// full says so, both in the stop's brief and in continue's refusal, rather than
// sending the reader to --include directories that are already there.
func TestStackRegenHintReadsTheWorkspaceAfterRegenerateFull(t *testing.T) {
	t.Parallel()
	f := regenRepo(t, regenCat)
	regenBranch(t, f, map[string]string{"src/f.txt": "f\n", "gen/out.txt": "a\nf\n"})
	writeShipFile(t, f.Dir, "src/g.txt", "g\n")
	writeShipFile(t, f.Dir, "gen/out.txt", "a\nf\ng\n")
	mustRun(t, f.Env(), f.Dir, "git", "add", "src/g.txt", "gen/out.txt")
	mustRun(t, f.Env(), f.Dir, "git", "commit", "-qm", "second generated change")
	regenAdvanceTrunk(t, f, [2]string{"src/t.txt", "t\n"}, [2]string{"gen/out.txt", "a\nt\n"})

	ws, err := regenStop(t, f)
	if want := regenSection(regenCat) + " [--include <dir>]... [--full], from " + ws + " once every other file is resolved — the workspace is sparse"; !strings.Contains(err.Error(), want) {
		t.Fatalf("first brief = %v, want %q", err, want)
	}
	if _, _, err := runStackCmdIn(t, f, ws, "regenerate", "--full"); err != nil {
		t.Fatalf("regenerate --full: %v", err)
	}

	full := regenSection(regenCat) + ", from " + ws + " once every other file is resolved — every file is checked out there, and ccx sets up none of the generator's dependencies there"
	_, _, err = runStackCmdIn(t, f, ws, "continue")
	if err == nil {
		t.Fatal("continue succeeded, want the second gen/out.txt conflict to stop it")
	}
	for _, want := range []string{"conflicted files:\n  gen/out.txt\n", "checked out: every file\n", full + "\n"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("second brief = %q, want %q", err, want)
		}
	}
	if strings.Contains(err.Error(), "sparse") {
		t.Errorf("second brief = %q, want no sparse wording for a full workspace", err)
	}

	_, _, err = runStackCmdIn(t, f, ws, "continue")
	if err == nil || !strings.HasSuffix(err.Error(), full) || strings.Contains(err.Error(), "sparse") {
		t.Errorf("continue over the unresolved conflict = %v, want the refusal to end with %q", err, full)
	}
}

