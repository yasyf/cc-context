func TestStackRegenerateStopsCleanlyOnAFailingGenerator(t *testing.T) {
	t.Parallel()
	const run = "echo generated half > gen/out.txt; echo boom >&2; exit 3"
	f := regenRepo(t, run)
	regenBranch(t, f, map[string]string{"src/f.txt": "f\n", "gen/out.txt": "a\nf\n"})
	regenAdvanceTrunk(t, f, [2]string{"gen/out.txt", "a\nt\n"})
	feature := gitAt(t, f.Env(), f.Dir, "rev-parse", "feature")
	ws, _ := regenStop(t, f)

	_, _, err := runStackCmdIn(t, f, ws, "regenerate")
	if err == nil {
		t.Fatal("regenerate succeeded over a failing generator")
	}
	for _, want := range []string{"stack regenerate: regenerating gen/out.txt failed, and nothing was committed", "generator `" + run + "` exited 3", "output tail:\n  boom"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("regenerate = %v, want %q", err, want)
		}
	}
	if unmerged := gitAt(t, f.Env(), ws, "diff", "--name-only", "--diff-filter=U"); unmerged != "gen/out.txt" {
		t.Errorf("unmerged = %q, want gen/out.txt still conflicted", unmerged)
	}
	if got := gitAt(t, f.Env(), f.Dir, "rev-parse", "feature"); got != feature {
		t.Errorf("feature moved to %s past a failed generator", got)
	}

	out, _, err := runStackCmd(t, f, "abort")
	if err != nil || !strings.Contains(out, "aborted") {
		t.Fatalf("abort = %q, %v", out, err)
	}
	if _, err := os.Stat(ws); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("workspace after abort: %v, want it removed", err)
	}
	if got := gitAt(t, f.Env(), f.Dir, "rev-parse", "feature"); got != feature {
		t.Errorf("feature moved to %s across an abort", got)
	}
}

